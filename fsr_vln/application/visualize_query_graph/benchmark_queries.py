def get_queries(profile: str, spatial_reasoning_method: str) -> List[str]:
    """Return the benchmark query list for a given profile and spatial reasoning method.

    Args:
        profile: Scene profile name (e.g. "ic3f", "ic4f", "ic7f", "sh3f").
        spatial_reasoning_method: One of "human_assign", "auto_region", "none".

    Returns:
        List of query instruction strings.

    Raises:
        KeyError: If profile or method is unknown.
    """
    if profile not in BENCHMARK_QUERIES:
        raise KeyError(
            f"Unknown profile '{profile}'. Available: {list(BENCHMARK_QUERIES.keys())}"
        )
    method_map = BENCHMARK_QUERIES[profile]
    if spatial_reasoning_method not in method_map:
        raise KeyError(
            f"Unknown spatial_reasoning_method '{spatial_reasoning_method}' for profile '{profile}'. "
            f"Available: {list(method_map.keys())}"
        )
    return method_map[spatial_reasoning_method]
